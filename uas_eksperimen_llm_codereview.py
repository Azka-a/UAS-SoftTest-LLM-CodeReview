def classify_pr(pr_text, use_rag=True):
    clean_text = str(pr_text or "")[:500]
    context, fallback_label = retrieve_top_k(clean_text, k=TOP_K)

    if use_rag:
        prompt = (
            f"Klasifikasikan Pull Request ke salah satu kategori [{CATEGORIES}] berdasarkan referensi Vector Search:\n"
            f"{context}\n\n"
            f"PR: \"{clean_text}\"\n"
            f"Jawab HANYA JSON valid: {{\"category\": \"...\", \"reason\": \"...\"}}"
        )
    else:
        prompt = (
            f"Klasifikasikan Pull Request ke salah satu kategori [{CATEGORIES}]:\n"
            f"PR: \"{clean_text}\"\n"
            f"Jawab HANYA JSON valid: {{\"category\": \"...\", \"reason\": \"...\"}}"
        )

    try:
        resp = call_gemini_with_timeout(prompt)
        raw = (resp.text or "").strip().replace("```json", "").replace("```", "").strip()
        start, end = raw.find("{"), raw.rfind("}")
        if start != -1 and end != -1:
            parsed = json.loads(raw[start:end+1])
            return parsed.get("category", fallback_label), parsed.get("reason", ""), prompt
        return fallback_label, raw[:80], prompt
    except FuturesTimeout:
        return fallback_label, "Timeout >15s (Fallback Top-1 Vector)", prompt
    except Exception as e:
        return fallback_label, f"Fallback Top-1 Vector ({type(e).__name__})", prompt

