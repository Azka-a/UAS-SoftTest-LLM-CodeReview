# Pola Heuristik H1 (exclude nama repo AI/GPT) & H4 (deteksi bantuan LLM di teks PR)
H1_EXCLUDE_REPO = re.compile(r"(chatgpt|gpt|openai|llm|gemini|copilot)", re.IGNORECASE)
H4_ASSIST_PATTERN = re.compile(
    r"(by|with|using|from|via|suggested by|generated by|refactored by|helped by)\s+"
    r"(chatgpt|gpt|gpt-4|gpt-3\.5|openai|gemini|copilot|claude)",
    re.IGNORECASE
)

def parse_iso(ts):
    return datetime.strptime(ts, "%Y-%m-%dT%H:%M:%SZ") if ts else None

def fetch_pr_group(query, is_assisted_label, target_count):
    collected = []
    page = 1
    while len(collected) < target_count and page <= 5:
        url = f"https://api.github.com/search/issues?q={query}&sort=updated&order=desc&per_page=30&page={page}"
        res = requests.get(url, headers=HEADERS)
        if res.status_code != 200:
            print("Stop/Error API:", res.status_code, res.text[:150])
            break
        items = res.json().get("items", [])
        if not items:
            break

        for item in items:
            if len(collected) >= target_count:
                break
            pr_url = item.get("pull_request", {}).get("url")
            if not pr_url:
                continue

            pr_res = requests.get(pr_url, headers=HEADERS)
            if pr_res.status_code != 200:
                continue
            pr = pr_res.json()

            # Cek status merged dan filter repo (>= 10 stars)
            if not pr.get("merged_at"):
                continue
            repo = pr.get("base", {}).get("repo", {})
            repo_name = repo.get("full_name", "")
            stars = repo.get("stargazers_count", 0)
            if stars < MIN_STARS:
                continue
            # Heuristik H1: hindari proyek yang memang tentang pembuatan library GPT
            if is_assisted_label == 1 and H1_EXCLUDE_REPO.search(repo_name):
                continue

            # Ambil review/komentar untuk memastikan >= 2 partisipan manusia & hitung fase PR
            author = pr.get("user", {}).get("login", "")
            reviews_res = requests.get(f"{pr_url}/reviews", headers=HEADERS)
            reviews = reviews_res.json() if reviews_res.status_code == 200 else []
            non_author_reviews = [
                r for r in reviews
                if r.get("user") and r["user"].get("login") != author
                and not r["user"].get("login", "").endswith("[bot]")
                and r.get("submitted_at")
            ]
            participants = {author} | {r["user"]["login"] for r in non_author_reviews}
            if len(participants) < MIN_PARTICIPANTS:
                continue

            # Validasi teks untuk kelompok LLM-Assisted
            pr_title = pr.get("title") or ""
            pr_body = pr.get("body") or ""
            combined_text = f"{pr_title} {pr_body}".replace("\n", " ").strip()
            if is_assisted_label == 1 and not H4_ASSIST_PATTERN.search(combined_text):
                continue

            # Hitung metrik waktu (dalam jam) sesuai definisi Paper Wajib
            created_at = parse_iso(pr["created_at"])
            merged_at = parse_iso(pr["merged_at"])
            repo_created = parse_iso(repo["created_at"])
            time_to_merge_h = max((merged_at - created_at).total_seconds() / 3600.0, 0.01)
            project_age_month = max((created_at - repo_created).days / 30.44, 0.1)

            rev_times = sorted([parse_iso(r["submitted_at"]) for r in non_author_reviews])
            at_review_h = max((rev_times[0] - created_at).total_seconds() / 3600.0, 0.0)
            at_waiting_h = max((rev_times[-1] - rev_times[0]).total_seconds() / 3600.0, 0.0) if len(rev_times) > 1 else 0.0
            approved_times = [parse_iso(r["submitted_at"]) for r in non_author_reviews if r.get("state") == "APPROVED"]
            at_change_h = max((approved_times[-1] - rev_times[-1]).total_seconds() / 3600.0, 0.0) if approved_times else 0.0

            collected.append({
                "pr_id": pr["id"],
                "repo_name": repo_name,
                "pr_url": pr["html_url"],
                "pr_title": pr_title[:200],
                "pr_text": combined_text[:1000],
                "stars": stars,
                "is_llm_assisted": is_assisted_label,
                "no_commits": pr.get("commits", 1),
                "pr_size": pr.get("additions", 0) + pr.get("deletions", 0),
                "no_changed_files": pr.get("changed_files", 1),
                "project_age_month": round(project_age_month, 2),
                "time_to_merge_h": round(time_to_merge_h, 4),
                "at_review_h": round(at_review_h, 4),
                "at_waiting_h": round(at_waiting_h, 4),
                "at_change_h": round(at_change_h, 4),
            })
            time.sleep(0.15)
        page += 1
        print(f"Label={is_assisted_label} | Page {page-1} selesai | Terkumpul: {len(collected)}")
    return collected

