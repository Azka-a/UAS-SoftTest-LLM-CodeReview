def retrieve_top_k(query_text, k=TOP_K):
    q_vec = embed_model.encode([query_text], show_progress_bar=False)
    sims = cosine_similarity(q_vec, kb_vectors)[0]
    top_idx = np.argsort(sims)[::-1][:k]
    lines = [
        f"- Contoh: \"{kb_df.iloc[i]['text']}\" => Kategori: {kb_df.iloc[i]['label']} (Sim: {sims[i]:.3f})"
        for i in top_idx
    ]
    return "\n".join(lines), kb_df.iloc[top_idx[0]]["label"]

def call_gemini_with_timeout(prompt, timeout_sec=API_TIMEOUT_SEC):
    def _req():
        return client.models.generate_content(
            model=MODEL_NAME,
            contents=prompt,
            config=types.GenerateContentConfig(temperature=0.0, max_output_tokens=150)
        )
    with ThreadPoolExecutor(max_workers=1) as ex:
        fut = ex.submit(_req)
        return fut.result(timeout=timeout_sec)

